export type DocumentFileType = 'pdf' | 'txt' | 'csv';

export type DocumentParseStatus = 'parsed' | 'empty' | 'error';

export type PipelineStage =
  | 'brief_submitted'
  | 'requirements_ready'
  | 'agent_built'
  | 'evaluated'
  | 'optimized';

export interface StoredDocument {
  id: string;
  projectId: string;
  originalName: string;
  storedFilename: string;
  fileType: DocumentFileType;
  mimeType: string;
  sizeBytes: number;
  uploadedAt: string;
  charCount: number;
  lineCount: number;
  pageCount: number | null;
  csvHeaders?: string[];
  csvRowCount?: number;
  csvSampleRows?: Record<string, string>[];
  previewText: string;
  parseStatus: DocumentParseStatus;
  parseNote?: string;
}

export interface StoredExtractedDocument {
  documentId: string;
  projectId: string;
  documentName: string;
  fileType: DocumentFileType;
  sizeBytes: number;
  parseStatus: DocumentParseStatus;
  parseNote?: string;
  csvHeaders?: string[];
  csvRowCount?: number;
  extractedText: string;
}

export interface AgentProject {
  id: string;
  name: string;
  domain: string;
  brief: string;
  stage: PipelineStage;
  createdAt: string;
  updatedAt: string;
  documents: StoredDocument[];
  // Reserved for upcoming pipeline stages; always null until generated by real API workflows
  requirements: null;
  agentConfig: null;
  evaluation: null;
  optimization: null;
  report: null;
}

export interface ProjectSummary {
  id: string;
  name: string;
  domain: string;
  brief: string;
  stage: PipelineStage;
  createdAt: string;
  updatedAt: string;
  documentCount: number;
  totalDocumentBytes: number;
}
